"""Build the Ghostty themes from palette.toml.

    python3 scripts/build_ghostty.py           # write extras/ghostty/critical-rhino-{dark,light}
    python3 scripts/build_ghostty.py --check   # fail (exit 1) if they're stale or a pairing is unreadable

A Ghostty theme is a config file. This one sets every option that decides what
color text is drawn in or on, and the check measures each pair the way Ghostty
draws it:

    text            the foreground and ANSI colors at their minimums (normals 4.5:1,
                    brights 3:1) on the background, and on the selection, since
                    selected text keeps its own color (selection-foreground = cell-foreground)
    bold            bold-color = bright draws bold text in the bright colors, so it's
                    set only where every bright reads at its normal color's minimum
    cursor          3:1 against the background, the selection and every surface an
                    editor draws under it; the character under a block cursor at 4.5:1
    search          text on both match highlights at 4.5:1
    faint           SGR 2 text is drawn at faint-opacity: the lowest opacity, in steps of
                    0.05, at which every text color stays at 3:1 however it's blended
    unfocused split Ghostty dims unfocused splits to 70%: every text color at 3:1

Faint text is measured both ways Ghostty can blend it. Its text shader applies the
faint opacity in linear light under `alpha-blending = linear` or `linear-corrected`
(the Linux default; the correction only adjusts glyph edges), and on sRGB values
under `native` (the macOS default). Linear blending pulls dark text toward a light
background much harder, so it decides the light variant's opacity; sRGB decides
dark's. Unfocused splits are dimmed by a translucent overlay the window draws over
the terminal (a CSS widget in GTK), measured as an sRGB blend.

Black and bright white are exempt (in each variant one is the text color and the
other nearly the background). The split divider is decoration, as borders are in
the other targets. If `ghostty` is installed, the check also has it validate both
files.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import rhino

THEME_DIR = rhino.ROOT / "extras" / "ghostty"
UNFOCUSED_SPLIT_OPACITY = 0.7  # Ghostty's default; the theme leaves it alone
TEXT_COLORS = ("foreground",) + rhino.ANSI[1:]  # what programs print text in: fg, red ... white
FAINT_STEP = 0.05


def palette(v: rhino.Variant) -> dict[str, str]:
    """Each ANSI name and the foreground, as Ghostty draws them."""
    return {"foreground": v.t("foreground")} | dict(zip(rhino.ANSI_NAMES, rhino.terminal_colors(v), strict=True))


BLENDS = {"sRGB": rhino.composite, "linear": rhino.composite_linear}  # see the module docstring


def faint_opacity(v: rhino.Variant) -> float:
    """The lowest opacity at which every text color, drawn faint, stays at 3:1 on the background
    under both blends."""
    bg, colors = v.t("background"), palette(v)
    steps = round(1 / FAINT_STEP)
    for i in range(1, steps + 1):
        alpha = round(i * FAINT_STEP, 2)
        if all(rhino.contrast(over(colors[n], alpha, bg, blend), bg) >= rhino.DIM_MIN
               for n in TEXT_COLORS for blend in BLENDS):
            return alpha
    return 1.0


def over(fg: str, alpha: float, bg: str, blend: str = "sRGB") -> str:
    return BLENDS[blend](rhino.Color(fg, alpha), bg)


def bold_is_bright(v: rhino.Variant) -> bool:
    """Bold text may use the bright colors only if each bright reads at its normal color's minimum."""
    colors, under = palette(v), surfaces(v)
    for name in rhino.ANSI:
        minimum = rhino.TERMINAL_MIN.get(name)
        if minimum and any(rhino.contrast(colors[f"bright_{name}"], s) < minimum for s in under.values()):
            return False
    return True


def surfaces(v: rhino.Variant) -> dict[str, str]:
    """What terminal text is drawn on: the background, and the selection."""
    bg = v.t("background")
    return {"background": bg, "selection": rhino.composite(v.term["selection"], bg)}


def theme(v: rhino.Variant) -> list[tuple[str, str] | str]:
    """The theme as (key, value) pairs, with comment lines as plain strings."""
    colors, under = palette(v), surfaces(v)
    cursor = rhino.composite(v.term["cursor"], v.t("background"))
    faint = faint_opacity(v)
    lines: list[tuple[str, str] | str] = [
        f"# Critical Rhino, {v.name}, for Ghostty.",
        "# Generated by scripts/build_ghostty.py from palette.toml; don't edit by hand.",
        "",
        ("background", v.t("background")),
        ("foreground", colors["foreground"]),
        "",
        "# ANSI colors. The normals are text (4.5:1); the brights are lighter accents (3:1).",
        *[("palette", f"{i}={colors[n]}") for i, n in enumerate(rhino.ANSI_NAMES)],
        "",
        "# Selected text keeps its own color; every text color reads on the selection.",
        ("selection-background", under["selection"]),
        ("selection-foreground", "cell-foreground"),
        "",
        "# The character under a block cursor is black or cream, whichever reads on it.",
        ("cursor-color", cursor),
        ("cursor-text", v.on(cursor)),
        "",
        "# Search matches, the same highlights as in the editors.",
        ("search-background", v.u("search")),
        ("search-foreground", v.u("search_foreground")),
        ("search-selected-background", v.u("search_current")),
        ("search-selected-foreground", v.u("search_current_foreground")),
        "",
    ]
    if bold_is_bright(v):
        lines += ["# Bold text in the bright colors, which here read at least as well as the normals.",
                  ("bold-color", "bright"), ""]
    else:
        lines += ["# Bold text keeps its color: the bright colors are too light to be text here.", ""]
    lines += [
        f"# Faint text at the lowest opacity that keeps every text color at {rhino.DIM_MIN:g}:1, however it's blended.",
        ("faint-opacity", f"{faint:g}"),
        "",
        ("split-divider-color", v.u("border")),
        "",
    ]
    return lines


class Terminal:
    """How Ghostty draws a cell in one variant, for checking the tools that print in the
    theme's colors (starship, fzf, lazygit). A color is None (the terminal's default), a
    palette index 0-255, or "#RRGGBB"."""

    def __init__(self, v: rhino.Variant) -> None:
        self.name = v.name
        self.colors = rhino.terminal_colors(v)
        self.foreground, self.background = v.t("foreground"), v.t("background")
        self.selection = surfaces(v)["selection"]
        self.bold_is_bright = bold_is_bright(v)
        self.faint = faint_opacity(v)

    def color(self, c: int | str | None, default: str) -> str:
        if c is None:
            return default
        if isinstance(c, str):
            return c.upper()
        return self.colors[c] if c < 16 else xterm(c)

    def draw(self, fg: int | str | None = None, bg: int | str | None = None, *, bold: bool = False,
             faint: bool = False, reverse: bool = False) -> list[tuple[str, str]]:
        """(text, background) as drawn: one pair, or for faint text one per way it can be blended."""
        if bold and self.bold_is_bright and isinstance(fg, int) and fg < 8:
            fg += 8
        text, under = self.color(fg, self.foreground), self.color(bg, self.background)
        if reverse:
            text, under = under, text
        if not faint:
            return [(text, under)]
        return [(over(text, self.faint, under, blend), under) for blend in BLENDS]


def xterm(i: int) -> str:
    """Colors 16-255 of the 256-color palette, which the theme leaves at xterm's values."""
    if i >= 232:
        r = g = b = 8 + 10 * (i - 232)
    else:
        steps = (0, 95, 135, 175, 215, 255)
        r, g, b = steps[(i - 16) // 36], steps[(i - 16) // 6 % 6], steps[(i - 16) % 6]
    return f"#{r:02X}{g:02X}{b:02X}"


# --- tools drawn in the terminal -----------------------------------------------------

@dataclass(frozen=True)
class Pair:
    """Text a tool draws: what it is, how it's set (Terminal.draw's arguments) and its minimum."""
    label: str
    ink: dict
    minimum: float


def measure(term: Terminal, pairs: list[Pair]) -> tuple[list[str], list[str]]:
    """Each pair as the terminal draws it. Returns (errors, report lines)."""
    errors, report = [], []
    for p in pairs:
        low = min(rhino.contrast(fg, bg) for fg, bg in term.draw(**p.ink))
        below = low < p.minimum - 1e-9
        if below:
            errors.append(f"{term.name}: {p.label} is {low:.2f}:1, below {p.minimum:g}")
        report.append(f"  {p.label:58s} {low:5.2f}:1{f'  <- below {p.minimum:g}' if below else ''}")
    return errors, report


def measure_variants(data: dict, pairs: list[Pair], own: list[Pair] | None = None) -> tuple[list[str], list[str]]:
    """The pairs in every variant. `own` are pairs the tool hard-codes, which no setting
    reaches: measured and reported, not failed."""
    errors, report = [], []
    for name in rhino.appearances(data):
        term = Terminal(rhino.load_variant(data, name))
        e, r = measure(term, pairs)
        errors += e
        report += [f"===== {name} =====", *r]
        if own:
            report += ["  [the tool's own, not failed: no setting reaches these]", *measure(term, own)[1]]
        report.append("")
    return errors, report


Outputs = Callable[[dict], tuple[dict[Path, str], list[str], list[str]]]


def tool_main(tool: str, outputs: Outputs, validate: Callable[[list[Path]], list[str]] | None = None) -> int:
    """main() for a tool drawn in the terminal (starship, fzf, lazygit, tmux). `outputs`
    takes the palette and returns (files, errors, report); `tool` is also its make
    target. With --check, `validate` gets the files on disk and returns errors."""
    parser = argparse.ArgumentParser(description=f"Build the {tool} theme from palette.toml.")
    parser.add_argument("--check", action="store_true", help="fail if the theme is stale or a pair is unreadable")
    parser.add_argument("--report", action="store_true", help="print every measured pair")
    args = parser.parse_args()
    files, errors, report = outputs(rhino.load())
    if args.report:
        print("\n".join(report))
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        errors += [f"{p.relative_to(rhino.ROOT)} is stale; run make {tool}" for p in stale]
        if validate:
            errors += validate([p for p in files if p.exists()])
        for e in errors:
            print(f"- {e}")
        if errors:
            return 1
        print(f"OK: the {tool} theme is current{f', {tool} accepts it,' if validate else ''} "
              "and every pair it creates reads.")
        return 0
    for e in errors:
        print(f"- {e}", file=sys.stderr)
    if errors:
        return 1
    for path, text in files.items():
        if path in stale:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(rhino.ROOT)}")
    return 0


def render(lines: list[tuple[str, str] | str]) -> str:
    return "\n".join(x if isinstance(x, str) else f"{x[0]} = {x[1]}" for x in lines)


# --- checking ------------------------------------------------------------------------

def check(v: rhino.Variant, lines: list[tuple[str, str] | str]) -> tuple[list[str], list[str]]:
    """Measure every pair the theme creates. Returns (errors, report lines)."""
    keys: dict[str, str] = {}
    pal: dict[int, str] = {}
    for x in lines:
        if isinstance(x, tuple):
            if x[0] == "palette":
                i, hex_ = x[1].split("=")
                pal[int(i)] = hex_
            else:
                keys[x[0]] = x[1]
    colors = {"foreground": keys["foreground"]} | {n: pal[i] for i, n in enumerate(rhino.ANSI_NAMES)}
    bg = keys["background"]
    under = {"background": bg, "selection": keys["selection-background"]}
    errors, report = [], []

    def measure(label: str, fg: str, on: dict[str, str], minimum: float, show: bool = True) -> None:
        ratios = {s: rhino.contrast(fg, h) for s, h in on.items()}
        low = [s for s, r in ratios.items() if r < minimum - 1e-9]
        errors.extend(f"{v.name}: {label} is {ratios[s]:.2f}:1 on the {s}, below {minimum:g}" for s in low)
        if show:
            cols = "  ".join(f"{s} {r:5.2f}:1" for s, r in ratios.items())
            report.append(f"  {label:34s} {cols}{f'  <- below {minimum:g}' if low else ''}")

    assert keys["selection-foreground"] == "cell-foreground", "selected text is measured in its own color"
    report.append("[text] on the background and the selection")
    for name, hex_ in colors.items():
        if name in rhino.TERMINAL_MIN:
            measure(f"{name} {hex_}", hex_, under, rhino.TERMINAL_MIN[name])

    if keys.get("bold-color") == "bright":
        report.append("[bold] bold-color = bright: each bright at its normal color's minimum")
        for name in rhino.ANSI:
            if name in rhino.TERMINAL_MIN:
                b = colors[f"bright_{name}"]
                measure(f"bold {name} -> {b}", b, under, rhino.TERMINAL_MIN[name])
    else:
        report.append("[bold] bold text keeps its color (no new pairs)")

    cursor, text = keys["cursor-color"], keys["cursor-text"]
    report.append(f"[cursor] {cursor}: at least {rhino.CURSOR_MIN:g}:1 against what it's drawn over")
    drawn_over = under | {s: h for s, h in v.surfaces.items() if h not in under.values()}
    measure("cursor", cursor, drawn_over, rhino.CURSOR_MIN)
    measure(f"text under the cursor {text}", text, {"cursor": cursor}, rhino.TEXT_MIN)

    report.append("[search] text on the match highlights")
    measure("match", keys["search-foreground"], {"highlight": keys["search-background"]}, rhino.TEXT_MIN)
    measure("current match", keys["search-selected-foreground"],
            {"highlight": keys["search-selected-background"]}, rhino.TEXT_MIN)

    faint = float(keys["faint-opacity"])
    report.append(f"[faint] text at {faint:g} opacity, blended in sRGB (macOS) and linear light (Linux): "
                  f"at least {rhino.DIM_MIN:g}:1")
    for name in TEXT_COLORS:
        for blend in BLENDS:
            measure(f"faint {name} ({blend})", over(colors[name], faint, bg, blend), {"background": bg}, rhino.DIM_MIN)
    report.append(f"[unfocused split] text under the {UNFOCUSED_SPLIT_OPACITY:g} overlay: at least {rhino.DIM_MIN:g}:1")
    for name in TEXT_COLORS:
        measure(f"unfocused split {name}", over(colors[name], UNFOCUSED_SPLIT_OPACITY, bg), {"background": bg},
                rhino.DIM_MIN)
    return errors, report


def validate(paths: list[Path]) -> list[str]:
    """Have Ghostty itself load each theme file, if it's installed."""
    ghostty = shutil.which("ghostty")
    if not ghostty:
        return []
    errors = []
    for path in paths:
        # validate-config loads only the given file, so the user's own config isn't involved
        out = subprocess.run([ghostty, "+validate-config", f"--config-file={path}"],
                             capture_output=True, text=True, check=False)
        if out.returncode != 0 or out.stdout.strip() or out.stderr.strip():
            detail = (out.stdout + out.stderr).strip().replace("\n", "; ")
            errors.append(f"ghostty rejects {path.relative_to(rhino.ROOT)}: {detail or f'exit {out.returncode}'}")
    return errors


# --- main ----------------------------------------------------------------------------

def outputs(data: dict) -> tuple[dict[Path, str], list[str], list[str]]:
    files, errors, report = {}, [], []
    for name in rhino.appearances(data):
        v = rhino.load_variant(data, name)
        lines = theme(v)
        e, r = check(v, lines)
        errors += e
        report += [f"===== {name} =====", *r, ""]
        files[THEME_DIR / f"critical-rhino-{name}"] = render(lines)
    return files, errors, report


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the Ghostty themes from palette.toml.")
    parser.add_argument("--check", action="store_true", help="fail if the themes are stale or a pair is unreadable")
    parser.add_argument("--report", action="store_true", help="print every measured pair")
    args = parser.parse_args()
    files, errors, report = outputs(rhino.load())
    if args.report:
        print("\n".join(report))
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        errors += [f"{p.relative_to(rhino.ROOT)} is stale; run make ghostty" for p in stale]
        errors += validate([p for p in files if p.exists()])
        for e in errors:
            print(f"- {e}")
        if errors:
            return 1
        print(f"OK: Ghostty themes are current, Ghostty accepts them, and every pair they create reads "
              f"({len(files)} variants).")
        return 0
    for e in errors:
        print(f"- {e}", file=sys.stderr)
    if errors:
        return 1
    THEME_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in files.items():
        if path in stale:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(rhino.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
