"""Build the fzf theme from palette.toml.

    python3 scripts/build_fzf.py           # write extras/fzf/critical-rhino.sh
    python3 scripts/build_fzf.py --check   # fail (exit 1) if it's stale or a pairing is unreadable
    python3 scripts/build_fzf.py --report  # print every measured pair

fzf can't tell a dark terminal from a light one, so every color is one of the 16 or
the terminal's own, and switches with the terminal. The current line is the
editors' blue band, drawn in reverse video so its contrast is the blue's own on the
background. Each element is measured the way Ghostty draws it
(build_ghostty.Terminal), plain and bold, since fzf may draw any of them bold.
"""

from __future__ import annotations

import sys
from pathlib import Path

import build_ghostty
import rhino
from build_ghostty import Pair

THEME_FILE = rhino.ROOT / "extras" / "fzf" / "critical-rhino.sh"
ANSI_INDEX = {n: i for i, n in enumerate(rhino.ANSI)}

# Every element fzf 0.44 colors: (color, attributes, minimum). -1 is the terminal's own
# color. Marks (pointer, borders, scrollbars) are 3:1; text is 4.5:1.
T, M = rhino.TEXT_MIN, rhino.DIM_MIN
COLORS = {
    "fg": ("-1", "", T),
    "bg": ("-1", "", None),
    "hl": ("blue", "", T),                # matched characters, the editors' match highlight
    "fg+": ("blue", "regular:reverse", T),  # the current line: a blue band with the background's color on it
    "bg+": ("-1", "", None),
    "hl+": ("blue", "reverse:bold", T),   # matched characters on it, bold as in the editors
    "gutter": ("-1", "", None),
    "pointer": ("blue", "", M),
    "marker": ("magenta", "", M),
    "query": ("-1", "", T),
    "disabled": ("white", "", T),
    "prompt": ("blue", "", T),
    "info": ("white", "", T),
    "spinner": ("yellow", "", M),
    "header": ("cyan", "", T),
    "label": ("white", "", T),
    "border": ("bright-black", "", M),
    "separator": ("bright-black", "", M),
    "scrollbar": ("bright-black", "", M),
    "preview-fg": ("-1", "", T),
    "preview-bg": ("-1", "", None),
    "preview-border": ("bright-black", "", M),
    "preview-scrollbar": ("bright-black", "", M),
    "preview-label": ("white", "", T),
}


def color(name: str) -> int | None:
    if name == "-1":
        return None
    bright = name.startswith("bright-")
    return ANSI_INDEX[name.removeprefix("bright-")] + 8 * bright


def spec() -> str:
    parts = ["16"] + [f"{e}:{c}" + (f":{a}" if a else "") for e, (c, a, _) in COLORS.items()]
    return ",".join(parts)


def theme_file() -> str:
    return "\n".join([
        "# Critical Rhino for fzf.",
        "# Generated by scripts/build_fzf.py; don't edit by hand.",
        "#",
        "# fzf can't tell a dark terminal from a light one, so every color is one of the",
        "# terminal's 16 or its own, and switches with the terminal. The current line is the",
        "# editors' blue band, drawn in reverse video so it reads in both.",
        "#",
        "# Source it from ~/.bashrc, before fzf's key bindings:",
        "#   . ~/path/to/critical-rhino/extras/fzf/critical-rhino.sh",
        "",
        f'export FZF_DEFAULT_OPTS="${{FZF_DEFAULT_OPTS:+$FZF_DEFAULT_OPTS }}--color={spec()}"',
        "",
    ])


def pairs() -> list[Pair]:
    """Each element on what it's drawn on. Every background is the terminal's own, so the
    pairs are the element's color on it, swapped where reversed. fzf may draw any of them
    bold, so each is measured both ways."""
    found = []
    for element, (c, attrs, minimum) in COLORS.items():
        if minimum is None:
            assert c == "-1", f"fzf {element}: backgrounds stay the terminal's, so every pair here holds"
            continue
        for bold in (False, True):
            if bold and "bold" in attrs:
                continue
            ink = {"fg": color(c), "reverse": "reverse" in attrs, "bold": bold or "bold" in attrs}
            found.append(Pair(f"{element} ({c}{':' + attrs if attrs else ''}){' bold' if bold else ''}", ink, minimum))
    return found


def outputs(data: dict) -> tuple[dict[Path, str], list[str], list[str]]:
    errors, report = build_ghostty.measure_variants(data, pairs())
    return {THEME_FILE: theme_file()}, errors, report


if __name__ == "__main__":
    sys.exit(build_ghostty.tool_main("fzf", outputs))
