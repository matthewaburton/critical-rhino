"""Build the lazygit theme from palette.toml.

    python3 scripts/build_lazygit.py           # write extras/lazygit/critical-rhino.yml
    python3 scripts/build_lazygit.py --check   # fail (exit 1) if it's stale or a pairing is unreadable
    python3 scripts/build_lazygit.py --report  # print every measured pair

lazygit asks the terminal for its background (OSC 11) to pick a dark or light theme,
but tmux answers from a copy it takes when the client attaches, so after the desktop
switches it can be wrong until you reattach. So the theme doesn't depend on the
answer: every color it sets reads in both variants. Almost everything lazygit draws
is one of the 16 already. The selected line is the editors' focused row, cream on
the selection blue, with every span's color replaced by cream; in unfocused panels
it's that blue with its color taken out.

Two things lazygit hard-codes stay its own: search matches in black on yellow and
cyan, and the selected commit's graph line in bright white, which in light is the
background. They're measured and reported, not failed. Every pair is measured the
way Ghostty draws it (build_ghostty.Terminal).
"""

from __future__ import annotations

import sys
from pathlib import Path

import build_ghostty
import rhino
from build_ghostty import Pair

THEME_FILE = rhino.ROOT / "extras" / "lazygit" / "critical-rhino.yml"
INACTIVE_CHROMA = 0.03   # the unfocused selection: the selection blue with most of its color taken out
NAMES = {"red": 1, "green": 2, "yellow": 3, "blue": 4, "magenta": 5, "cyan": 6, "white": 7}
# What lazygit hard-codes that no theme key reaches.
OWN = {
    "search match (black on yellow)": {"fg": 0, "bg": 3},
    "current search match (black on cyan)": {"fg": 0, "bg": 6},
    "selected commit's graph line (bold bright white)": {"fg": 15, "bold": True},
}


def colors(data: dict) -> dict[str, str]:
    """The hex colors the lazygit theme uses, which must be the same in every variant."""
    seen = {}
    for name in rhino.appearances(data):
        v = rhino.load_variant(data, name)
        selection = v.u("selection")
        L, _, H = rhino.oklch(selection)
        seen[name] = {"selection": selection, "selection_foreground": v.u("selection_foreground"),
                      "inactive": rhino.oklch_to_hex(L, INACTIVE_CHROMA, H)}
    first = next(iter(seen.values()))
    if any(c != first for c in seen.values()):
        raise rhino.PaletteError("lazygit can't reliably tell dark from light (tmux caches the background), so "
                                 f"its selection must be the same in every variant: {seen}")
    return first


def theme(data: dict) -> list[tuple[str, str, str]]:
    """(key, YAML value, why) for gui.theme."""
    c = colors(data)
    return [
        ("activeBorderColor", "[blue, bold]", "the focused panel's frame and title, blue as the editors' focus"),
        ("inactiveBorderColor", "[white]", "other frames and titles, in the secondary text color"),
        ("searchingActiveBorderColor", "[cyan, bold]", "lazygit's default"),
        ("optionsTextColor", "[blue]", "lazygit's default"),
        ("selectedLineBgColor", f'["{c["selection"]}"]', "the editors' focused row"),
        ("selectedLineFgColor", f'["{c["selection_foreground"]}"]',
         "replaces every span's color on the selected line, so it reads on both bands"),
        ("inactiveViewSelectedLineBgColor", f'["{c["inactive"]}"]', "the selection blue with its color taken out"),
        ("cherryPickedCommitFgColor", "[cyan, reverse]", "copied commits as a cyan pill"),
        ("cherryPickedCommitBgColor", "[default]", ""),
        ("unstagedChangesColor", "[red]", "lazygit's default"),
        ("defaultFgColor", "[default]", "lazygit's default"),
    ]


def theme_file(data: dict) -> str:
    lines = [
        "# Critical Rhino for lazygit.",
        "# Generated by scripts/build_lazygit.py; don't edit by hand.",
        "#",
        "# lazygit draws almost everything in the terminal's 16 colors, which switch with the",
        "# terminal. Every color set here reads in dark and light alike, because lazygit's own",
        "# guess at which it's in can be stale under tmux.",
        "#",
        "# Use it as ~/.config/lazygit/config.yml, or alongside your own config:",
        '#   export LG_CONFIG_FILE="$HOME/.config/lazygit/config.yml,$HOME/path/to/critical-rhino/extras/lazygit/critical-rhino.yml"',
        "",
        "gui:",
        "  theme:",
    ]
    for key, value, why in theme(data):
        lines.append(f"    {key}: {value}" + (f"  # {why}" if why else ""))
    lines += [
        "    authorColors:",
        '      "*": white  # one color for every author and the graph; lazygit\'s own colors are 24-bit,',
        "                  # picked for whichever background it guesses, and miss 4.5:1 when it guesses wrong",
        "",
    ]
    return "\n".join(lines)


def color(value: str) -> int | str | None:
    return value if value.startswith("#") else NAMES.get(value)


def pairs(data: dict) -> list[Pair]:
    """The pairs the theme is responsible for."""
    c = colors(data)
    cream, bands = c["selection_foreground"], {"selected line": c["selection"], "unfocused selected line": c["inactive"]}
    found = []
    for where, band in bands.items():
        found.append(Pair(f"{where}: cream on {band}", {"fg": cream, "bg": band}, rhino.TEXT_MIN))
        found.append(Pair(f"copied commit on the {where}: {band} on cream", {"fg": cream, "bg": band, "reverse": True},
                          rhino.TEXT_MIN))
    found.append(Pair("copied commit: cyan pill", {"fg": 6, "reverse": True}, rhino.TEXT_MIN))
    for key, value, _ in theme(data):
        words = value.strip("[]").replace('"', "").split(", ")
        if key.endswith(("BorderColor", "TextColor")) or key == "unstagedChangesColor":
            found.append(Pair(f"{key} {value}", {"fg": color(words[0]), "bold": "bold" in words}, rhino.TEXT_MIN))
    found.append(Pair("authors and graph: white", {"fg": 7}, rhino.TEXT_MIN))
    for name, i in NAMES.items():   # hard-coded spans: hashes, status letters, refs, menus ...
        if name != "white":
            found += [Pair(f"text in {name}", {"fg": i}, rhino.TEXT_MIN),
                      Pair(f"text in bold {name}", {"fg": i, "bold": True}, rhino.TEXT_MIN)]
    found.append(Pair("dim yellow (an upstream that was only rewritten)", {"fg": 3, "faint": True}, rhino.DIM_MIN))
    return found


def outputs(data: dict) -> tuple[dict[Path, str], list[str], list[str]]:
    own = [Pair(label, ink, rhino.TEXT_MIN) for label, ink in OWN.items()]
    errors, report = build_ghostty.measure_variants(data, pairs(data), own)
    return {THEME_FILE: theme_file(data)}, errors, report


if __name__ == "__main__":
    sys.exit(build_ghostty.tool_main("lazygit", outputs))
