"""Build the tmux theme from palette.toml.

    python3 scripts/build_tmux.py           # write extras/tmux/critical-rhino.conf
    python3 scripts/build_tmux.py --check   # fail (exit 1) if it's stale, a pairing is unreadable or tmux rejects it
    python3 scripts/build_tmux.py --report  # print every measured pair

tmux draws its status bar, borders, messages and copy-mode highlights in colors
its options set. Its defaults put black text on green, yellow, cyan or magenta,
fine in dark but about 2.5:1 in light, where black is the text color. The theme
sets every one of those options to one of the terminal's 16 colors or its own,
never a fixed value, so tmux follows the terminal between dark and light.
Highlights are reverse video: a palette color as the block, with text in the
terminal's background color, so each reads at the color's own contrast on the
background in both variants.

Each style is measured the way Ghostty draws it (build_ghostty.Terminal), plain and
bold, since a format can add bold. Pane titles are drawn in the border colors, so
borders are held to 4.5:1 too. If `tmux` is installed, the check also has it load
the file in a private server with no other config and confirms every option took.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import build_ghostty
import rhino
from build_ghostty import Pair

THEME_FILE = rhino.ROOT / "extras" / "tmux" / "critical-rhino.conf"
COLORS = {n: i for i, n in enumerate(rhino.ANSI)} | {f"bright{n}": i + 8 for i, n in enumerate(rhino.ANSI)}

# (option, style, why). A style may be a tmux conditional, #{?flag,style,style}.
STYLES = [
    ("status-style", "fg=default,bg=default", "the status bar on the terminal's own background"),
    ("window-status-style", "fg=blue", "window names in blue"),
    ("window-status-current-style", "fg=blue,bg=default,reverse", "the current window as a blue block"),
    ("pane-border-style", "#{?pane_synchronized,fg=red,fg=white}",
     "gray borders, all red while input goes to every pane"),
    ("pane-active-border-style", "#{?pane_synchronized,fg=red,fg=blue}", "the active pane's border in blue"),
    ("message-style", "fg=yellow,bg=default,reverse", "messages as a yellow block, like the terminal's search highlight"),
    ("message-command-style", "fg=yellow,bg=default,reverse", "the command prompt"),
    ("mode-style", "fg=blue,bg=default,reverse", "the copy-mode selection and the selected row in choosers"),
    ("copy-mode-match-style", "fg=yellow,bg=default,reverse", "search matches"),
    ("copy-mode-current-match-style", "fg=red,bg=default,reverse", "the current match (the terminal has no orange)"),
    ("copy-mode-mark-style", "fg=magenta,bg=default,reverse", "the copy-mode mark"),
    ("menu-selected-style", "fg=blue,bg=default,reverse", "the selected menu item"),
]
CONDITIONAL = re.compile(r"#\{\?(\w+),([^,{}]*),([^,{}]*)\}")  # branches with commas escape them as #,


def branches(style: str) -> list[tuple[str, str]]:
    """(when, style) for each branch of a style: one for a plain style, two for a conditional."""
    m = CONDITIONAL.fullmatch(style)
    if not m:
        return [("", style)]
    flag, yes, no = m.groups()
    return [(f" ({flag})", yes), (f" (not {flag})", no)]


def ink(style: str) -> dict:
    """Terminal.draw arguments for a tmux style such as "fg=blue,bg=default,reverse"."""
    drawn: dict = {}
    for word in style.split(","):
        key, _, value = word.partition("=")
        if key in ("fg", "bg"):
            if value != "default" and value not in COLORS:
                raise ValueError(f"{value} isn't one of the terminal's 16 colors or its own")
            drawn[key] = COLORS.get(value)
        elif key == "reverse":
            drawn["reverse"] = True
        elif key == "bold":
            drawn["bold"] = True
        else:
            raise ValueError(f"unexpected {word!r}")
    return drawn


def theme_file() -> str:
    lines = [
        "# Critical Rhino for tmux.",
        "# Generated by scripts/build_tmux.py; don't edit by hand.",
        "#",
        "# Every color is one of the terminal's 16 or its own, never a fixed value, so tmux",
        "# follows the terminal between dark and light. Highlights are reverse video: a",
        "# palette color as the block, with text in the terminal's background color, which",
        "# reads in both. tmux's defaults put black text on a color, about 2.5:1 in light.",
        "#",
        "# Source it from ~/.tmux.conf:",
        "#   source-file ~/path/to/critical-rhino/extras/tmux/critical-rhino.conf",
    ]
    for option, style, why in STYLES:
        lines += ["", f"# {why[0].upper()}{why[1:]}", f'set -g {option} "{style}"']
    return "\n".join(lines) + "\n"


def pairs() -> tuple[list[Pair], list[str]]:
    found, errors = [], []
    for option, style, _ in STYLES:
        for when, branch in branches(style):
            try:
                drawn = ink(branch)
            except ValueError as e:
                errors.append(f"tmux {option} = {branch!r}: {e}")
                continue
            for bold in (False, True):
                found.append(Pair(f"{option}{when} ({branch}){' bold' if bold else ''}", drawn | {"bold": bold},
                                  rhino.TEXT_MIN))
    return found, errors


def validate(paths: list[Path]) -> list[str]:
    """Have tmux load the theme in a private server with no other config, and confirm
    every option holds its value."""
    tmux = shutil.which("tmux")
    if not tmux or THEME_FILE not in paths:
        return []
    path = THEME_FILE
    env = {k: v for k, v in os.environ.items() if k != "TMUX"}
    # tmux leaves its socket file behind when the server stops, so the socket lives in a
    # folder that's removed afterwards.
    with tempfile.TemporaryDirectory(prefix="rhino-tmux-check-") as tmp:
        base = [tmux, "-S", str(Path(tmp) / "socket"), "-f", os.devnull]

        def run(*args: str) -> subprocess.CompletedProcess:
            return subprocess.run([*base, *args], capture_output=True, text=True, env=env, check=False)

        try:
            out = run("new-session", "-d", ";", "source-file", str(path))
            if out.returncode != 0 or out.stderr.strip():
                detail = (out.stdout + out.stderr).strip().replace("\n", "; ")
                return [f"tmux rejects {path.relative_to(rhino.ROOT)}: {detail or f'exit {out.returncode}'}"]
            errors = []
            for option, style, _ in STYLES:
                got = run("show-options", "-gv", option).stdout.strip()
                if got != style:
                    errors.append(f"tmux has {option} = {got!r} after loading the theme, not {style!r}")
            return errors
        finally:
            run("kill-server")


def outputs(data: dict) -> tuple[dict[Path, str], list[str], list[str]]:
    found, errors = pairs()
    e, report = build_ghostty.measure_variants(data, found)
    return {THEME_FILE: theme_file()}, errors + e, report


if __name__ == "__main__":
    sys.exit(build_ghostty.tool_main("tmux", outputs, validate))
